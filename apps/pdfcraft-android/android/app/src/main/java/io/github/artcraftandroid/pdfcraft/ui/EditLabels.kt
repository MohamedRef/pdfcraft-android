/**
 * What Undo or Redo would do, said in the app's language: the engine's [wording] looked up in
 * [EditLabelResources] (a batch's name is its [value]), or the engine's [english] label when the
 * wording is one the app doesn't know yet.
 */
internal fun editLabel(wording: String?, value: String?, english: String, say: (Int, String?) -> String): String {
    val (key, hole) = if (wording == "{batch}") value to null else wording to value
    val id = key?.let { EditLabelResources[it] } ?: return english
    return say(id, hole)
}

private fun say(id: Int, value: String?): String =
    if (value != null) io.github.artcraftandroid.pdfcraft.text(id, value) else io.github.artcraftandroid.pdfcraft.text(id)

/** What Undo would undo, in the app's language (#118). */
internal val DocumentInfo.undoLabel: String?
    get() = undo?.let { editLabel(undoWording, undoValue, it, ::say) }

/** What Redo would redo, in the app's language (#118). */
internal val DocumentInfo.redoLabel: String?
    get() = redo?.let { editLabel(redoWording, redoValue, it, ::say) }
